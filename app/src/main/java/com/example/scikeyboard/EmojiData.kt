    /** এই ইমোজি/চিহ্ন ফোনের ফন্টে আছে কি না। */
    fun supported(s: String): Boolean {
        glyphCache[s]?.let { return it }
        val ok = try {
            paint.hasGlyph(s) || (s.contains('\uFE0F') && paint.hasGlyph(s.replace("\uFE0F", "")))
        } catch (e: Throwable) { true }
        glyphCache[s] = ok
        return ok
    }

