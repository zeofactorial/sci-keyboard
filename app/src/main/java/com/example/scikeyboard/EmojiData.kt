        private var cache: List<String>? = null

        /** ফোনে যেগুলো সত্যিই দেখানো যায় শুধু সেগুলো। */
        fun items(): List<String> {
            cache?.let { return it }
            val all = raw.split(sep).filter { it.isNotEmpty() }
            val ok = all.filter { EmojiData.supported(it) }
            val res = if (ok.isEmpty()) all else ok
            cache = res
            return res
        }
    }

