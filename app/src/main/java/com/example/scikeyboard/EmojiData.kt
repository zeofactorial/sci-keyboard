    /** [e] ইমোজির ৫টি skin tone রূপ; না থাকলে null। */
    fun skinVariants(e: String): List<String>? {
        if (e.isEmpty()) return null
        val first = e.codePointAt(0)
        if (first !in MOD_BASES) return null
        var rest = e.substring(Character.charCount(first))
        if (rest.startsWith("\uFE0F")) rest = rest.substring(1)
        val base = String(Character.toChars(first))
        val out = ArrayList<String>()
        for (tone in 0x1F3FB..0x1F3FF) {
            val v = base + String(Character.toChars(tone)) + rest
            if (supported(v)) out.add(v)
        }
        return if (out.size == 5) out else null
    }

